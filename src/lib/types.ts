/**
 * StartupOS — Core domain types.
 *
 * These types describe the complete business ecosystem produced by the
 * multi-agent orchestration engine. Every agent reads from and writes to
 * a strongly-typed slice of {@link BusinessPackage}.
 */

export type BusinessStyle =
  | "Premium / Luxury"
  | "Modern / Minimal"
  | "Bold / Energetic"
  | "Friendly / Approachable"
  | "Corporate / Professional"
  | "Playful / Creative"
  | "Tech / Futuristic"
  | "Organic / Natural";

export interface BusinessInput {
  idea: string;
  audience: string;
  location: string;
  budget: string;
  style: BusinessStyle;
}

/* ----------------------------- Brand ----------------------------------- */

export interface ColorSwatch {
  name: string;
  hex: string;
  role: "primary" | "secondary" | "accent" | "neutral-dark" | "neutral-light" | "surface";
  usage: string;
}

export interface TypographyScaleItem {
  label: string;
  sizePx: number;
  weight: number;
  lineHeight: number;
  letterSpacing: string;
}

export interface TypographySystem {
  headingFont: string;
  headingFallback: string;
  bodyFont: string;
  bodyFallback: string;
  googleFontsHref: string;
  scale: TypographyScaleItem[];
}

export interface BrandGuideline {
  title: string;
  rule: string;
}

export interface Brand {
  name: string;
  slogan: string;
  description: string;
  /** Origin/brand story narrative (why the business exists). */
  story: string;
  mission: string;
  vision: string;
  values: string[];
  voice: string[];
  personality: string[];
  logo: LogoAsset;
  palette: ColorSwatch[];
  typography: TypographySystem;
  guidelines: BrandGuideline[];
}

export interface LogoAsset {
  /** True only when real logo images were generated by the image model. */
  generated: boolean;
  /** Public URL of the primary generated logo (full lockup). Empty when not generated. */
  imageUrl: string;
  /** Public URL of the generated icon / app mark. Empty when not generated. */
  iconUrl: string;
  /** The exact prompt used to generate the primary logo (for transparency). */
  prompt: string;
  /** Image model used, or null when generation was unavailable. */
  model: string | null;
  /** Explicit status so the UI never shows a fabricated placeholder. */
  status: "generated" | "unavailable" | "error";
  concept: string;
}

