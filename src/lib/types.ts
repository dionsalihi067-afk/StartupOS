/* ------------------------------ Research ------------------------------- */

/** A normalized real web search result. */
export interface SearchResult {
  title: string;
  url: string;
  snippet: string;
}

/** Why a research-backed section may have no data. */
export type ResearchStatus = "ok" | "search-not-configured" | "no-results" | "error";

/* ----------------------------- Competitors ----------------------------- */

export interface Competitor {
  name: string;
  /** Relationship to the new business. */
  type: "direct" | "indirect" | "local";
  /** Business category / segment inferred from the search result. */
  category: string;
  description: string;
  /** Real website discovered via web search. */
  website: string;
  strengths: string[];
  weaknesses: string[];
  /** Source URLs that back this competitor record. */
  sources: string[];
}

export interface CompetitorAnalysis {
  /** True only when real competitor data was retrieved from live web search. */
  available: boolean;
  status: ResearchStatus;
  /** Search provider used (e.g. "tavily"), or null. */
  provider: string | null;
  /** Queries actually executed against the search provider. */
  queries: string[];
  marketOverview: string;
  competitors: Competitor[];
  swot: {
    strengths: string[];
    weaknesses: string[];
    opportunities: string[];
    threats: string[];
  };
  differentiation: string[];
  opportunityGaps: string[];
  /** All raw search results used, for transparency / citations. */
  sources: SearchResult[];
}

/* --------------------------- Market research --------------------------- */

export interface MarketInsight {
  insight: string;
  /** Source URLs grounding this insight. */
  sources: string[];
}

export interface MarketResearch {
  available: boolean;
  status: ResearchStatus;
  provider: string | null;
  queries: string[];
  summary: string;
  trends: MarketInsight[];
  painPoints: MarketInsight[];
  demandSignals: MarketInsight[];
  opportunities: MarketInsight[];
  sources: SearchResult[];
}

/* ----------------------------- Pricing --------------------------------- */

export interface PricingTier {
  name: string;
  price: string;
  cadence: string;
  tagline: string;
  features: string[];
  highlighted: boolean;
  cta: string;
}

export interface SubscriptionOption {
  name: string;
  price: string;
  cadence: string;
  /** What's distinctive about this billing option (e.g. savings). */
  note: string;
}

/**
 * A transparent profit *projection* derived from the user's budget and tier
 * pricing. Every number is computed from stated assumptions — never presented
 * as a market fact.
 */
export interface ProfitEstimation {
  assumptions: string[];
  monthlyCustomers: number;
  avgRevenuePerCustomer: string;
  estimatedMonthlyRevenue: string;
  estimatedMonthlyCosts: string;
  estimatedMonthlyProfit: string;
  margin: string;
}

export interface PricingStrategy {
  model: string;
  /** How the business makes money (e.g. subscriptions, one-off, retainers). */
  revenueModel: string;
  rationale: string;
  tiers: PricingTier[];
  psychology: string[];
  upsells: string[];
  subscriptionOptions: SubscriptionOption[];
  profitEstimation: ProfitEstimation;
}

