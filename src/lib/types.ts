/* ----------------------------- Package --------------------------------- */

export interface BusinessPackage {
  id: string;
  createdAt: string;
  input: BusinessInput;
  brand: Brand;
  website: Website;
  marketing: Marketing;
  competitors: CompetitorAnalysis;
  marketResearch: MarketResearch;
  pricing: PricingStrategy;
  persona: CustomerPersona;
  salesFunnel: SalesFunnelStage[];
  growth: GrowthPhase[];
  launch: LaunchPlan;
  /** Metadata describing how the package was produced. */
  meta: {
    engine: "llm" | "deterministic" | "hybrid";
    /** Live search provider used for research (null when none configured). */
    searchProvider: string | null;
    durationMs: number;
    agentLog: AgentLogEntry[];
  };
}

export interface AgentLogEntry {
  agent: string;
  status: "ok" | "fallback" | "error";
  source: "llm" | "deterministic";
  durationMs: number;
  note?: string;
}

/* --------------------------- Orchestration ----------------------------- */

export type AgentKey =
  | "brand"
  | "design"
  | "logo"
  | "website"
  | "seo"
  | "marketing"
  | "email"
  | "whatsapp"
  | "pricing"
  | "competitor"
  | "market"
  | "persona"
  | "growth"
  | "launch"
  | "publisher";

export interface OrchestrationEvent {
  type: "agent-start" | "agent-complete" | "agent-error" | "progress" | "complete" | "error";
  agent?: AgentKey;
  label?: string;
  message?: string;
  progress?: number;
  source?: "llm" | "deterministic";
  /** Present only on the terminal "complete" event. */
  result?: BusinessPackage;
}
